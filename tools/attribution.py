"""Public, reproducible code and firmware anchors for component attribution."""
import json
import re
from datetime import date
from urllib.parse import urlsplit


def read_attributions(root, registry):
    catalog = json.loads((root/'data/attribution-evidence.json').read_text(encoding='utf-8'))
    if catalog.get('schema_version') != 1 or not isinstance(catalog.get('items'), list):
        raise ValueError('Invalid attribution catalog schema')
    seen, lines = set(), set()
    for item in catalog['items']:
        ident = item.get('id', '')
        if (not re.fullmatch('[a-z0-9-]+', ident) or ident in seen
                or not isinstance(item.get('title'), str) or not item['title'].strip()
                or not item.get('lines') or len(set(item['lines'])) != len(item['lines'])
                or any(line not in registry or line in lines for line in item['lines'])):
            raise ValueError('Invalid attribution item: ' + ident)
        seen.add(ident)
        lines.update(item['lines'])
        date.fromisoformat(item['reviewed_at'])
        if any(not isinstance(item.get('summary', {}).get(lang), str)
               or not item['summary'][lang].strip() for lang in ('en', 'ru', 'es', 'zh')):
            raise ValueError('Missing attribution translation: ' + ident)
        if not item.get('sources') or not item.get('artifacts'):
            raise ValueError('Missing attribution evidence: ' + ident)
        for artifact in item['artifacts']:
            url = artifact.get('url', '')
            parsed = urlsplit(url)
            if (parsed.scheme != 'https' or not parsed.hostname or parsed.username or parsed.password
                    or any(c.isspace() or ord(c) < 32 for c in url)
                    or artifact.get('kind') not in ('code', 'firmware')
                    or any(not isinstance(artifact.get(key), str) or not artifact[key].strip()
                           for key in ('title', 'marker'))):
                raise ValueError('Invalid attribution artifact: ' + ident)
            for key, pattern in (('commit', '[0-9a-f]{40}'), ('sha256', '[0-9a-f]{64}')):
                if key in artifact and not re.fullmatch(pattern, artifact[key]):
                    raise ValueError('Invalid attribution ' + key + ': ' + ident)
            if artifact['kind'] == 'firmware' and not artifact.get('sha256'):
                raise ValueError('Missing attribution firmware hash: ' + ident)
            if parsed.hostname == 'github.com':
                commit = artifact.get('commit')
                if not commit or '/blob/' + commit + '/' not in parsed.path:
                    raise ValueError('Attribution GitHub file must be pinned: ' + ident)
    return catalog


def render_attributions(catalog):
    out = ['# Attribution evidence: code and firmware', '',
           'Public source files and firmware binaries behind identified TRON-069 components.',
           'Each link names the inspected file, the matching marker and a fixed revision.',
           'SHA-256 values refer to that file, not its containing archive.',
           'A reference device anchors a software component; it does not identify every',
           'device matching the same response. Third-party files are linked at their source.', '',
           '[Open the atlas](https://scadastrangelove.github.io/TRON-069/#lang=en&tab=wanted)',
           '· [Open firmware searches](WANTED.md)', '',
           '<!-- Generated by tools/build-map.py from data/attribution-evidence.json. -->', '']
    for item in catalog['items']:
        out += [f'<a id="{item["id"]}"></a>', '## ' + item['title'], '',
                item['summary']['en'], '', 'Reviewed: **' + item['reviewed_at'] + '**.', '',
                'Atlas lines: ' + ', '.join('`' + s + '`' for s in item['lines']) + '.', '']
        for artifact in item['artifacts']:
            out += ['### [' + artifact['title'] + '](' + artifact['url'] + ')', '',
                    'Type: ' + ('source code' if artifact['kind'] == 'code' else 'firmware binary') + '.', '',
                    'Fingerprint: `' + artifact['marker'] + '`.', '']
            for key, title in (('version', 'Version'), ('commit', 'Commit'), ('sha256', 'SHA-256')):
                if artifact.get(key):
                    out += [title + ': `' + artifact[key] + '`.', '']
        out += ['Research: ' + ' · '.join(
            '[' + s['file'] + '](' + s['file'] + ('#' + s['anchor'] if s.get('anchor') else '') + ')'
            for s in item['sources']), '']
    return '\n'.join(out)
