"""Shared public firmware requests, issue links and generated contributor guide."""
import json
import re
from datetime import date
from urllib.parse import urlencode

ISSUE_BASE = 'https://github.com/scadastrangelove/TRON-069/issues/new'
STATUSES = ('wanted', 'received', 'verified', 'attributed')


def issue_url(ident='other', title='Another TR-069 implementation'):
    return ISSUE_BASE + '?' + urlencode({
        'template': 'bring-your-own-tr069.yml',
        'title': '[BYO TR-069] ' + title,
        'target': ident + ' — ' + title,
    })


def read_wanted(root, registry):
    catalog = json.loads((root/'data/wanted.json').read_text(encoding='utf-8'))
    if catalog.get('schema_version') != 1 or not isinstance(catalog.get('items'), list):
        raise ValueError('Invalid wanted catalog schema')
    date.fromisoformat(catalog['reviewed_at'])
    seen = set()
    for item in catalog['items']:
        ident = item.get('id', '')
        if (not re.fullmatch('[a-z0-9-]+', ident) or ident in seen
                or item.get('status') not in STATUSES
                or not isinstance(item.get('title'), str) or not item['title'].strip()
                or (item.get('line') is not None and item['line'] not in registry)):
            raise ValueError('Invalid wanted item: ' + ident)
        seen.add(ident)
        for field in ('context', 'needed') + (('result',) if item['status'] != 'wanted' else ()):
            if any(not isinstance(item.get(field, {}).get(lang), str)
                   or not item[field][lang].strip() for lang in ('en', 'ru', 'es', 'zh')):
                raise ValueError('Missing wanted translation: ' + ident + '/' + field)
        if not item.get('sources'):
            raise ValueError('Missing wanted sources: ' + ident)
        if not isinstance(item.get('credits', []), list) or any(
                not isinstance(name, str) or not name.strip() for name in item.get('credits', [])):
            raise ValueError('Invalid wanted credits: ' + ident)
        item['issue_url'] = issue_url(ident, item['title'])
    catalog['other_url'] = issue_url()
    return catalog


def render_wanted(catalog):
    """English repo entry point, generated from the same catalog as the atlas."""
    out = ['# Bring Your Own TR-069', '',
           '> We have the banners. You may have the firmware.', '',
           'Help identify the software behind the signatures in TRON-069. Public firmware',
           'downloads, GPL archives, component sources and documentation can close a search.',
           'Known models and versions help us connect a response to its implementation.', '',
           '[Open this list in the atlas](https://scadastrangelove.github.io/TRON-069/#lang=en&tab=wanted).', '',
           '## What to send', '',
           '- A public source link and how you identified the device or component.',
           '- Model, hardware revision and firmware version, when known.',
           '- Country and operator, when relevant; no subscriber or device addresses.',
           '- An observation date and sanitized response fingerprint, if available.',
           '- SHA-256 and the original filename, if available.',
           '- Your preferred credit, or a request for no public credit.', '',
           'Use the **I have this** link below to open a prefilled GitHub issue.',
           'Partial evidence and corrections are welcome; say which details are unknown.', '',
           '**Public issues are for links and sanitized fingerprint evidence.** Do not attach',
           'firmware images, raw dumps, configurations, credentials or unpublished vulnerability',
           'details. For non-public material, ask only to arrange a private transfer before',
           'sharing it. A transfer channel must be agreed with a maintainer; an issue is public.', '',
           '## Research status', '',
           '**Wanted → Received → Verified → Attributed**', '',
           '- **Wanted:** the evidence below is still missing.',
           '- **Received:** a candidate has arrived; its relevance is being reviewed.',
           '- **Verified:** provenance and the matching fingerprint have been checked.',
           '- **Attributed:** the component is identified and public evidence is linked.', '',
           'Maintainers update the status after review. Confirmed results receive an atlas',
           'source, a dated news entry and contributor credit as requested. Closed searches',
           'remain here. A candidate that does not match leaves the search open.', '',
           'Last reviewed: **' + catalog['reviewed_at'] + '**.', '',
           '<!-- Generated by tools/build-map.py from data/wanted.json. Edit the catalog. -->', '']
    items = sorted(catalog['items'], key=lambda item: item['status'] == 'attributed')
    for item in items:
        out += [f'<a id="{item["id"]}"></a>', '## ' + item['title'], '',
                '**Status: ' + item['status'].title() + '**', '',
                item['context']['en'], '', '**What we need:** ' + item['needed']['en'], '']
        if item.get('result'):
            out += [item['result']['en'], '']
        if item.get('credits'):
            out += ['Credit: ' + ', '.join(item['credits']) + '.', '']
        out += ['Sources: ' + ' · '.join(
            '[' + s['file'] + '](' + s['file'] + ('#' + s['anchor'] if s.get('anchor') else '') + ')'
            for s in item['sources']), '', '[I have this](' + item['issue_url'] + ')', '']
    out += ['## Something else?', '',
            'Unknown signatures, other implementations and evidence that corrects an existing',
            'attribution are welcome.', '', '[Bring another TR-069](' + catalog['other_url'] + ')', '',
            '## Maintaining this list', '',
            'Edit `data/wanted.json`, including all four languages, sources, status and optional',
            '`result` and `credits`. Statuses after Wanted require a translated result describing',
            'what has been received or established; link the supporting public evidence.',
            'Run `python3 tools/build-map.py` to regenerate this document and both atlas entry points.',
            'The list is editorial and does not change with the selected measurement snapshot.', '']
    return '\n'.join(out)
